#!/usr/bin/env python3
"""Embed a file as a C byte array: tools/embed.py web/index.html web_index_html > web_page.h"""
import sys

path, name = sys.argv[1], sys.argv[2]
data = open(path, "rb").read()
out = sys.stdout
out.write("/* Generated by tools/embed.py from %s; do not edit. */\n" % path)
out.write("#ifndef %s_H\n#define %s_H\n" % (name.upper(), name.upper()))
out.write("static const unsigned char %s[] = {\n" % name)
for i in range(0, len(data), 16):
    out.write("  " + ",".join("0x%02x" % b for b in data[i:i+16]) + ",\n")
out.write("};\nstatic const size_t %s_len = %d;\n#endif\n" % (name, len(data)))
